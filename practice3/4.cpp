// Задача 4: «Подъём по лестнице»
// Условие: вы поднимаетесь по лестнице из n ступенек.
// За один шаг можно подняться на 1 или на 2 ступеньки.
// Сколько различных способов добраться до вершины?

// Анализ DP:
// Состояние: DP[i] — число способов добраться до ступеньки i.
// Последний шаг: либо пришли с i-1, либо с i-2.
// Рекуррентность: DP[i] = DP[i-1] + DP[i-2].
// База: DP[0] = 1 (пустой путь), DP[1] = 1.

// Это числа Фибоначчи, но с другим сдвигом.

#include <iostream>
#include <vector>
using namespace std;

int climbStairs(int n) {
    if (n <= 1) return 1;
    vector<int> dp(n + 1);
    dp[0] = 1;
    dp[1] = 1;
    for (int i = 2; i <= n; i++) {
        dp[i] = dp[i - 1] + dp[i - 2];
    }
    return dp[n];
}

int main() {
    for (int n = 1; n <= 10; n++) {
        cout << "n = " << n << ": " << climbStairs(n) << endl;
    }
    return 0;
}

// Сложность: O(S · |coins|) по времени, O(S) по памяти.
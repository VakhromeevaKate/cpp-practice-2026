// Задача 2. Указатель: адрес, разыменование, переназначение
/**
 * Условие. Объявите int x = 42. Создайте указатель p на x. Выведите:
 - Значение x.
 - Адрес x (через &x).
 - Значение, на которое указывает p (через *p).
 - Адрес, хранящийся в p.
 Затем измените x через p и снова выведите x.
 После этого перенаправьте p на другую переменную y и покажите,
 что *p теперь выдаёт значение, которое было в y.
 */

 #include <iostream>

int main() {
    int x = 42;
    int y = 13;

    int* p = &x;                                // указатель на x

    std::cout << "x = " << x << "\n";           // 42
    std::cout << "&x = " << &x << "\n";         // адрес x
    std::cout << "*p = " << *p << "\n";         // 42
    std::cout << "p = " << p << "\n";           // тот же адрес

    std::cout << "y = " << y << "\n";         // y 
    std::cout << "&y = " << &y << "\n";         // адрес y

    *p = 100;                                   // меняем x через указатель
    std::cout << "x после *p = 100: " << x << "\n"; // 100

    p = &y;                                     // переназначаем указатель
    std::cout << "*p после p = &y: " << *p << "\n"; // 13
    std::cout << "p = " << p << "\n";           // адрес y
    return 0;
}